import { agentLeft } from '../agents/agentLeft'
import { createManagerPty } from '../manager/managerPty'
import { createPtyWiring } from '../terminal/pty/ptyWiring'
import type { AgentContext } from './agentServices'

export function createPaneServices(ctx: AgentContext) {
  const {
    agentRunning,
    agentWork,
    artifactFolders,
    closedPanes,
    hibernatedPanes,
    hostPaneGrants,
    injectSecrets,
    keepShellsOn,
    keptAttention,
    keptPaneEnv,
    keptPlumbing,
    keptShells,
    keptShellsProgram,
    mainStrings,
    movingPanes,
    openWaits,
    paneLauncherDir,
    paneWaking,
    paneLifecycleEvents,
    portRequests,
    primaryWindowId,
    ptys,
    recoveryHeld,
    releaseMergedSandbox,
    restoreKeptAttention,
    scratchFolders,
    services,
    startedAgents,
    terminalState,
    windows,
    withKeptProcess,
    workspaceSandboxes,
  } = ctx

  const {
    loadPty,
    feedPty,
    trackPty,
    killPty,
    hibernatePty,
    paneActivity,
    foregroundProgram,
    agentCwd,
    sandboxReadRules,
    ptyPid,
    paneOutput,
    paneIo,
    releasePtyFlow,
    hidePtyFlow,
    attachMirror,
    ptyWrite,
    attachPhoneObserver,
    windowOfPane,
    startRecovery,
    finishRecovery,
    releaseWindowPtys,
    holdPtys,
    releaseMovingPane,
    attachPty,
  } = createPtyWiring({
    ptys,
    movingPanes,
    recoveryHeld,
    closedPanes,
    openWaits,
    agentRunning,
    agentWork,
    keptAttention,
    services,
    hibernatedPanes,
    startedAgents,
    terminalState,
    keptShells,
    paneWaking,
    paneLifecycleEvents,
    workspaceSandboxes,
    injectSecrets,
    keptPlumbing,
    portRequests,
    releaseMergedSandbox,
    restoreKeptAttention,
    windows,
    scratchFolders,
    artifactFolders,
    hostPaneGrants,
    paneLauncherDir,
    keepShellsOn,
    keptShellsProgram,
    withKeptProcess,
    keptPaneEnv,
    bannerText: () => mainStrings().native.paneBanner,
  })

  agentRunning.whenStopped((paneId) =>
    agentLeft(
      {
        waking: (id) => paneWaking.has(id),
        sandboxed: (id) => ptys.get(id)?.sandboxed,
        program: foregroundProgram,
      },
      paneId,
    ),
  )

  const { spawnManagerPty } = createManagerPty({ loadPty, primaryWindowId, trackPty, feedPty })

  return {
    killPty,
    hibernatePty,
    paneActivity,
    foregroundProgram,
    agentCwd,
    sandboxReadRules,
    ptyPid,
    paneOutput,
    paneIo,
    releasePtyFlow,
    hidePtyFlow,
    attachMirror,
    ptyWrite,
    attachPhoneObserver,
    windowOfPane,
    startRecovery,
    finishRecovery,
    releaseWindowPtys,
    holdPtys,
    releaseMovingPane,
    attachPty,
    spawnManagerPty,
  }
}

export type PaneContext = AgentContext & ReturnType<typeof createPaneServices>
